create or replace function public.admin_media_create(
  p_original_name text,
  p_declared_mime text,
  p_declared_bytes bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_actor uuid;
  v_id uuid := pg_catalog.gen_random_uuid();
  v_name text := pg_catalog.btrim(coalesce(p_original_name, ''));
  v_path text;
begin
  v_actor := public.assert_admin();

  if v_name = '' or pg_catalog.length(v_name) > 120 or v_name ~ '[[:cntrl:]]' then
    raise exception 'original name is invalid' using errcode = '22023';
  end if;
  if p_declared_mime not in ('image/png', 'image/jpeg', 'image/webp') then
    raise exception 'declared type is not allowed' using errcode = '22023';
  end if;
  if p_declared_bytes is null or p_declared_bytes < 1 or p_declared_bytes > 15728640 then
    raise exception 'declared size is not allowed' using errcode = '22023';
  end if;

  v_path := 'media/' || v_id::text;

  insert into public.media_assets (
    id, storage_path, logical_path, status,
    original_name, declared_mime, declared_bytes, created_by
  )
  values (
    v_id, v_path, v_path, 'pending',
    v_name, p_declared_mime, p_declared_bytes, v_actor
  );

  return pg_catalog.jsonb_build_object(
    'id', v_id,
    'logical_path', v_path,
    'storage_path', v_path,
    'bucket', 'ccafe-media',
    'status', 'pending',
    'max_bytes', 15728640,
    'created_at', pg_catalog.now()
  );
end;
$fn$;

create or replace function public.admin_media_finalize(
  p_asset_id uuid,
  p_token_sha256 text,
  p_mime text,
  p_bytes bigint,
  p_width integer,
  p_height integer,
  p_pixel_count bigint,
  p_sha256 text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_actor uuid;
  v_now timestamptz := pg_catalog.now();
  v_asset public.media_assets%rowtype;
  v_expected text;
  v_pixels bigint;
begin
  v_actor := public.assert_admin();

  select s.value_sha256
  into v_expected
  from public.media_secrets as s
  where s.name = 'finalize';

  if v_expected is null
    or p_token_sha256 is null
    or p_token_sha256 !~ '^[0-9a-f]{64}$'
    or p_token_sha256 <> v_expected
  then
    raise exception 'finalize token is invalid' using errcode = '42501';
  end if;

  if p_mime is null or p_mime not in ('image/png', 'image/jpeg', 'image/webp') then
    raise exception 'verified type is not allowed' using errcode = '22023';
  end if;
  if p_bytes is null or p_bytes < 1 or p_bytes > 15728640 then
    raise exception 'verified size is not allowed' using errcode = '22023';
  end if;
  if p_width is null or p_height is null
    or p_width < 1 or p_width > 8000
    or p_height < 1 or p_height > 8000
  then
    raise exception 'verified dimensions are not allowed' using errcode = '22023';
  end if;
  v_pixels := p_width::bigint * p_height::bigint;
  if p_pixel_count is null or p_pixel_count <> v_pixels or v_pixels > 32000000 then
    raise exception 'verified pixel count is not allowed' using errcode = '22023';
  end if;
  if p_sha256 is null or p_sha256 !~ '^[0-9a-f]{64}$' then
    raise exception 'verified digest is not allowed' using errcode = '22023';
  end if;

  select *
  into v_asset
  from public.media_assets as a
  where a.id = p_asset_id
  for update;

  if not found then
    raise exception 'media asset not found' using errcode = 'P0002';
  end if;
  if v_asset.created_by is distinct from v_actor then
    raise exception 'media asset belongs to another uploader' using errcode = '42501';
  end if;

  if v_asset.status = 'approved' then
    -- Retry-safe: the same verification result returns the existing approval and
    -- does not create another asset, version, or timestamp change.
    if v_asset.mime = p_mime
      and v_asset.bytes = p_bytes
      and v_asset.width = p_width
      and v_asset.height = p_height
      and v_asset.pixel_count = p_pixel_count
      and v_asset.sha256 = p_sha256
    then
      return pg_catalog.jsonb_build_object(
        'id', v_asset.id,
        'logical_path', v_asset.logical_path,
        'status', 'approved',
        'mime', v_asset.mime,
        'bytes', v_asset.bytes,
        'width', v_asset.width,
        'height', v_asset.height,
        'pixel_count', v_asset.pixel_count,
        'sha256', v_asset.sha256,
        'finalized_at', v_asset.finalized_at,
        'idempotent', true
      );
    end if;

    raise exception 'media asset was already verified with different bytes' using errcode = 'PT409';
  end if;

  if v_asset.status <> 'pending' then
    raise exception 'media asset is not pending' using errcode = 'PT409';
  end if;

  if not exists (
    select 1
    from storage.objects as o
    where o.bucket_id = 'ccafe-media'
      and o.name = v_asset.storage_path
  ) then
    raise exception 'uploaded object is missing' using errcode = 'P0002';
  end if;

  update public.media_assets as a
  set status = 'approved',
      mime = p_mime,
      bytes = p_bytes,
      width = p_width,
      height = p_height,
      pixel_count = p_pixel_count,
      sha256 = p_sha256,
      verified_by = v_actor,
      verified_at = v_now,
      finalized_at = v_now,
      failure_reason = null,
      verify_detail = pg_catalog.jsonb_build_object(
        'mime', p_mime,
        'bytes', p_bytes,
        'width', p_width,
        'height', p_height,
        'pixel_count', p_pixel_count,
        'sha256', p_sha256
      )
  where a.id = p_asset_id
  returning * into v_asset;

  return pg_catalog.jsonb_build_object(
    'id', v_asset.id,
    'logical_path', v_asset.logical_path,
    'status', 'approved',
    'mime', v_asset.mime,
    'bytes', v_asset.bytes,
    'width', v_asset.width,
    'height', v_asset.height,
    'pixel_count', v_asset.pixel_count,
    'sha256', v_asset.sha256,
    'finalized_at', v_asset.finalized_at,
    'idempotent', false
  );
end;
$fn$;

create or replace function public.admin_media_fail(
  p_asset_id uuid,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_actor uuid;
  v_asset public.media_assets%rowtype;
  v_reason text := pg_catalog.left(pg_catalog.btrim(coalesce(p_reason, '')), 200);
begin
  v_actor := public.assert_admin();

  select *
  into v_asset
  from public.media_assets as a
  where a.id = p_asset_id
  for update;

  if not found then
    raise exception 'media asset not found' using errcode = 'P0002';
  end if;
  if v_asset.created_by is distinct from v_actor then
    raise exception 'media asset belongs to another uploader' using errcode = '42501';
  end if;

  if v_asset.status = 'approved' then
    raise exception 'approved media cannot be marked failed' using errcode = 'PT409';
  end if;
  if v_asset.status = 'failed' then
    return pg_catalog.jsonb_build_object(
      'id', v_asset.id,
      'status', 'failed',
      'failure_reason', v_asset.failure_reason,
      'idempotent', true
    );
  end if;

  update public.media_assets as a
  set status = 'failed',
      failure_reason = nullif(v_reason, ''),
      verified_by = null,
      verified_at = null,
      finalized_at = null
  where a.id = p_asset_id
  returning * into v_asset;

  return pg_catalog.jsonb_build_object(
    'id', v_asset.id,
    'status', 'failed',
    'failure_reason', v_asset.failure_reason,
    'idempotent', false
  );
end;
$fn$;

-- ---------------------------------------------------------------------------
-- Content validation: media/<uuid> must be an approved asset
--
-- The body is the same as the original validator except for the image branch.
-- Original assets/ paths remain valid exactly as before.
-- ---------------------------------------------------------------------------

create or replace function public.assert_content_value(
  p_value jsonb,
  p_path text,
  p_depth integer
)
returns void
language plpgsql
security invoker
set search_path = ''
as $fn$
declare
  v_type text := pg_catalog.jsonb_typeof(p_value);
  v_key text;
  v_child jsonb;
  v_text text;
  v_index integer := 0;
begin
  if p_depth > 8 then
    raise exception 'content is nested too deeply' using errcode = '22023';
  end if;

  if v_type = 'object' then
    if (select count(*) from pg_catalog.jsonb_object_keys(p_value)) > 50 then
      raise exception 'content object has too many keys' using errcode = '22023';
    end if;

    for v_key, v_child in
      select key, value from pg_catalog.jsonb_each(p_value)
    loop
      if length(v_key) > 80 then
        raise exception 'content key is invalid' using errcode = '22023';
      end if;
      perform public.assert_content_value(v_child, p_path || '.' || v_key, p_depth + 1);
    end loop;
  elsif v_type = 'array' then
    if pg_catalog.jsonb_array_length(p_value) > 200 then
      raise exception 'content array is too long' using errcode = '22023';
    end if;

    for v_child in
      select value from pg_catalog.jsonb_array_elements(p_value)
    loop
      v_index := v_index + 1;
      perform public.assert_content_value(
        v_child,
        p_path || '[' || v_index || ']',
        p_depth + 1
      );
    end loop;
  elsif v_type = 'string' then
    v_text := p_value #>> '{}';

    if length(v_text) > 4000 then
      raise exception 'content string is too long' using errcode = '22023';
    end if;

    if p_path ~ '\.href$' then
      if v_text <> '' and not (
        v_text ~ '^#[A-Za-z0-9_-]+$'
        or v_text ~* '^(https?://|tel:|mailto:|sms:)'
        or (v_text ~ '^/' and v_text !~ '^//')
        or v_text in ('@phone', '@maps', '@instagram')
      ) then
        raise exception 'unsafe link in content' using errcode = '22023';
      end if;
    elsif p_path ~ '\.phoneIntl$' then
      if v_text <> '' and v_text !~ '^\+?[0-9 ()-]+$' then
        raise exception 'phoneIntl must contain only a phone number' using errcode = '22023';
      end if;
    elsif p_path ~ '\.(mapsUrl|instagramUrl|siteUrl)$' then
      if v_text <> '' and v_text !~* '^https?://' then
        raise exception 'URL fields must use http or https' using errcode = '22023';
      end if;
    elsif p_path ~ '\.(image|mark|logo|favicon|touchIcon|ogImage)$' then
      if v_text <> '' then
        if v_text ~ '^assets/[A-Za-z0-9_./-]+$' and v_text not like '%..%' then
          -- Original bundled asset: unchanged, read-only behavior.
          null;
        elsif v_text ~ '^media/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
          and exists (
            select 1
            from public.media_assets as a
            where a.logical_path = v_text
              and a.status = 'approved'
          )
        then
          -- Approved private upload.
          null;
        else
          raise exception 'image paths must reference an approved media asset' using errcode = '22023';
        end if;
      end if;
    end if;
  end if;
end;
$fn$;

create or replace function public.assert_publishable_media(p_content jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $fn$
begin
  -- Uploaded media references are allowed in a draft (so the admin can preview
  -- them) but never in a published version in this phase. Published content is
  -- public and the private bucket must not become a public image host.
  if p_content::text ~ '"media/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"' then
    raise exception 'private media cannot be published' using errcode = 'CC001';
  end if;
end;
$fn$;

-- ---------------------------------------------------------------------------
-- Publish/restore: block private media at the database boundary
--
-- These bodies match 20261108020000_conflict_sqlstate.sql with one added call
-- to assert_publishable_media before any row is changed. Publishing original
-- assets/ content is unaffected.
-- ---------------------------------------------------------------------------

create or replace function public.admin_publish(
  p_expected_version bigint,
  p_expected_draft_revision uuid,
  p_content jsonb,
  p_note text,
  p_operation_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_actor uuid;
  v_now timestamptz := pg_catalog.now();
  v_site public.site_content%rowtype;
  v_draft public.draft%rowtype;
  v_existing jsonb;
  v_content jsonb;
  v_source text;
  v_note text;
  v_request jsonb;
  v_version bigint;
  v_result jsonb;
begin
  v_actor := public.assert_admin();

  if p_operation_id is null then
    raise exception 'operation id is required' using errcode = '22023';
  end if;
  if length(coalesce(p_note, '')) > 200 then
    raise exception 'note is too long' using errcode = '22023';
  end if;
  v_note := nullif(p_note, '');

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('ccafe.content.lock')::bigint);

  v_request := pg_catalog.jsonb_build_object(
    'expected_version', p_expected_version,
    'expected_draft_revision', p_expected_draft_revision,
    'content_md5', case when p_content is null then null else pg_catalog.md5(p_content::text) end,
    'note', v_note
  );

  v_existing := public.find_operation(p_operation_id, v_actor, 'publish', v_request);
  if v_existing is not null then
    return v_existing;
  end if;

  select *
  into v_site
  from public.site_content as s
  where s.id = 1
  for update;

  if not found then
    raise exception 'published content is not initialized' using errcode = '55000';
  end if;
  if v_site.version <> p_expected_version then
    raise exception 'stale published version' using errcode = 'PT409';
  end if;

  if p_expected_draft_revision is not null then
    if p_content is not null then
      raise exception 'content must be null when publishing a draft revision' using errcode = '22023';
    end if;

    select *
    into v_draft
    from public.draft as d
    where d.id = 1
    for update;

    if not found or v_draft.revision_id <> p_expected_draft_revision then
      raise exception 'stale draft revision' using errcode = 'PT409';
    end if;
    if v_draft.base_version <> v_site.version then
      raise exception 'draft is based on an older published version' using errcode = 'PT409';
    end if;

    v_content := v_draft.content;
    v_source := 'draft';
  else
    if p_content is null then
      raise exception 'content is required when no draft revision is supplied' using errcode = '22023';
    end if;

    v_content := p_content;
    v_source := 'content';
  end if;

  perform public.validate_content(v_content);
  perform public.assert_publishable_media(v_content);

  update public.site_content as s
  set version = v_site.version + 1,
      content = v_content,
      saved_at = v_now,
      saved_by = v_actor,
      purge_state = 'pending',
      purge_requested_at = null,
      purge_accepted_at = null,
      purge_error = null,
      purge_operation_id = null,
      public_check_id = null,
      public_check_state = 'pending',
      public_check_observed_version = null,
      public_check_at = null,
      public_check_detail = null
  where s.id = 1
  returning s.version into v_version;

  insert into public.content_history (
    version, content, note, created_at, created_by, operation_id
  )
  values (
    v_version, v_content, v_note, v_now, v_actor, p_operation_id
  );

  if p_expected_draft_revision is not null then
    delete from public.draft as d
    where d.id = 1
      and d.revision_id = p_expected_draft_revision;
  end if;

  perform public.trim_content_history();

  v_result := pg_catalog.jsonb_build_object(
    'version', v_version,
    'saved_at', v_now,
    'operation_id', p_operation_id,
    'source', v_source,
    'purge_state', 'pending',
    'public_check_state', 'pending'
  );

  insert into public.content_operations (operation_id, actor_id, kind, request, result)
  values (p_operation_id, v_actor, 'publish', v_request, v_result);

  return v_result;
end;
$fn$;

create or replace function public.admin_restore(
  p_history_id bigint,
  p_expected_version bigint,
  p_note text,
  p_operation_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_actor uuid;
  v_now timestamptz := pg_catalog.now();
  v_site public.site_content%rowtype;
  v_history public.content_history%rowtype;
  v_existing jsonb;
  v_version bigint;
  v_note text;
  v_request jsonb;
  v_result jsonb;
begin
  v_actor := public.assert_admin();

  if p_operation_id is null then
    raise exception 'operation id is required' using errcode = '22023';
  end if;
  if length(coalesce(p_note, '')) > 200 then
    raise exception 'note is too long' using errcode = '22023';
  end if;
  v_note := coalesce(nullif(p_note, ''), 'استعادة نسخة سابقة');

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('ccafe.content.lock')::bigint);

  v_request := pg_catalog.jsonb_build_object(
    'history_id', p_history_id,
    'expected_version', p_expected_version,
    'note', v_note
  );

  v_existing := public.find_operation(p_operation_id, v_actor, 'restore', v_request);
  if v_existing is not null then
    return v_existing;
  end if;

  select *
  into v_site
  from public.site_content as s
  where s.id = 1
  for update;

  if not found then
    raise exception 'published content is not initialized' using errcode = '55000';
  end if;
  if v_site.version <> p_expected_version then
    raise exception 'stale published version' using errcode = 'PT409';
  end if;

  select *
  into v_history
  from public.content_history as h
  where h.id = p_history_id;

  if not found then
    raise exception 'history version not found' using errcode = 'P0002';
  end if;

  perform public.validate_content(v_history.content);
  perform public.assert_publishable_media(v_history.content);

  update public.site_content as s
  set version = v_site.version + 1,
      content = v_history.content,
      saved_at = v_now,
      saved_by = v_actor,
      purge_state = 'pending',
      purge_requested_at = null,
      purge_accepted_at = null,
      purge_error = null,
      purge_operation_id = null,
      public_check_id = null,
      public_check_state = 'pending',
      public_check_observed_version = null,
      public_check_at = null,
      public_check_detail = null
  where s.id = 1
  returning s.version into v_version;

  insert into public.content_history (
    version, content, note, created_at, created_by, operation_id
  )
  values (
    v_version, v_history.content, v_note, v_now, v_actor, p_operation_id
  );

  perform public.trim_content_history();

  v_result := pg_catalog.jsonb_build_object(
    'version', v_version,
    'saved_at', v_now,
    'operation_id', p_operation_id,
    'source', 'restore',
    'restored_from', p_history_id,
    'purge_state', 'pending',
    'public_check_state', 'pending'
  );

  insert into public.content_operations (operation_id, actor_id, kind, request, result)
  values (p_operation_id, v_actor, 'restore', v_request, v_result);

  return v_result;
end;
