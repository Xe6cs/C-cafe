-- C Cafe media library: private Storage uploads, server-verified approval, and
-- an approved-only reference surface for the draft editor.
--
-- Scope:
--   * Adds public.media_assets (metadata for uploaded images), a private
--     storage bucket, Storage RLS policies, and admin RPCs.
--   * Original site assets under assets/ are NOT copied, replaced, or deleted.
--     They stay read-only and are listed by the application, not this schema.
--   * Content values may reference an approved upload as media/<asset-uuid>.
--     A pending/failed upload is never a valid content value.
--   * Publishing any content that still references an uploaded media asset is
--     rejected with SQLSTATE CC001. Original assets/ references keep working.
--
-- Security model:
--   * Browser uploads go directly to the private bucket with the admin JWT.
--     The upload path is generated by admin_media_create first; Storage RLS
--     only allows inserting exactly that pending path for its creator.
--   * There is no INSERT/UPDATE policy on media_assets. Status can only move
--     pending -> approved/failed through SECURITY DEFINER RPCs.
--   * admin_media_finalize requires a server-side finalize token whose SHA-256
--     fingerprint is stored here. The Netlify Function is the only holder of
--     the token; an admin JWT alone cannot mark bytes as verified.
--   * No service_role key is required or stored by this migration.
--
-- Cleanup:
--   * pending rows are abandoned explicitly (admin_media_fail) and the object
--     is removed through the Storage API by the server.
--   * failed rows keep their metadata for audit; their objects are deleted at
--     failure time and are never selectable as content.
--   * approved assets are intentionally not auto-deleted; removal is out of
--     scope for this phase.

begin;

-- ---------------------------------------------------------------------------
-- Media assets
-- ---------------------------------------------------------------------------

create table public.media_assets (
  id uuid primary key default gen_random_uuid(),
  storage_path text not null unique,
  logical_path text not null unique,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'failed')),
  original_name text not null,
  declared_mime text not null,
  declared_bytes bigint not null,
  mime text,
  bytes bigint,
  width integer,
  height integer,
  pixel_count bigint,
  sha256 text,
  failure_reason text,
  verify_detail jsonb,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  verified_by uuid references auth.users (id) on delete set null,
  verified_at timestamptz,
  finalized_at timestamptz,
  constraint media_assets_path_shape check (
    storage_path = logical_path
    and logical_path ~ '^media/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
  ),
  constraint media_assets_declared check (
    declared_mime in ('image/png', 'image/jpeg', 'image/webp')
    and declared_bytes between 1 and 15728640
  ),
  constraint media_assets_approved_shape check (
    status <> 'approved'
    or (
      mime in ('image/png', 'image/jpeg', 'image/webp')
      and bytes between 1 and 15728640
      and width between 1 and 8000
      and height between 1 and 8000
      and pixel_count between 1 and 32000000
      and sha256 ~ '^[0-9a-f]{64}$'
      and verified_at is not null
    )
  )
);

create index media_assets_status_idx
  on public.media_assets (status, created_at desc);

comment on table public.media_assets is
  'Private uploaded images. pending = bytes not verified yet; approved = server-verified and selectable; failed = rejected/abandoned. Only approved rows are valid content references.';
comment on column public.media_assets.logical_path is
  'Stable content reference (media/<uuid>) and the exact Storage object name. Replaces the former assets/-only rule for uploaded images.';
comment on column public.media_assets.sha256 is
  'SHA-256 of the exact uploaded bytes, computed server-side after download and decode verification.';

-- ---------------------------------------------------------------------------
-- Finalize credential fingerprint
--
-- Only the SHA-256 of CCAFE_MEDIA_FINALIZE_TOKEN is stored. The token itself
-- lives only in the Netlify Function environment. This proves that a finalize
-- call comes from the server component that actually decoded the bytes, not
-- from an admin JWT used directly against PostgREST.
--
-- The value seeded here is an inert placeholder, not the live verifier. A fresh
-- install must generate CCAFE_MEDIA_FINALIZE_TOKEN and replace public.media_secrets
-- with SHA-256(token); a restore loads the exported row instead.
-- ---------------------------------------------------------------------------

create table public.media_secrets (
  name text primary key,
  value_sha256 text not null check (value_sha256 ~ '^[0-9a-f]{64}$'),
  updated_at timestamptz not null default now()
);

comment on table public.media_secrets is
  'Server-only verifier fingerprints. No API role can read this table.';

insert into public.media_secrets (name, value_sha256)
values (
  'finalize',
  '3333333333333333333333333333333333333333333333333333333333333333'
);

-- ---------------------------------------------------------------------------
-- Storage bucket (private) and object policies
--
-- The bucket is created idempotently. allowed_mime_types is a second line of
-- defence (the browser can lie); the real check is the decode in the server.
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'ccafe-media',
  'ccafe-media',
  false,
  15728640,
  array['image/png', 'image/jpeg', 'image/webp']
)
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

-- Read: admins only. The bucket stays private; anonymous and non-admin users
-- cannot list or sign object URLs.
create policy ccafe_media_admin_read on storage.objects
  for select to authenticated
  using (bucket_id = 'ccafe-media' and public.is_admin());

-- Upload: only the exact pending path generated for this admin. No overwrite
-- is possible because object INSERT fails when the name already exists and the
-- path must still be pending. There is deliberately no UPDATE policy.
create policy ccafe_media_admin_upload on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'ccafe-media'
    and public.is_admin()
    and exists (
      select 1
      from public.media_assets as a
      where a.storage_path = storage.objects.name
        and a.status = 'pending'
        and a.created_by = auth.uid()
    )
  );

-- Delete: cleanup of a pending/failed upload by its creator only. Approved
-- assets cannot be deleted through the Storage API by admins.
create policy ccafe_media_admin_cleanup on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'ccafe-media'
    and public.is_admin()
    and exists (
      select 1
      from public.media_assets as a
      where a.storage_path = storage.objects.name
        and a.status in ('pending', 'failed')
        and a.created_by = auth.uid()
    )
  );

